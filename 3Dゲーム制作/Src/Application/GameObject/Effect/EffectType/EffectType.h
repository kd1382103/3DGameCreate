#pragma once

//==============================================================
// エフェクトの種類
//==============================================================
enum class EffectType
{
	//--------------------------
	// 攻撃関連
	//--------------------------
	Hit,			// 人間系の被弾・血しぶき
	Spark,			// 機械系の被弾・火花
	Slash,			// 通常攻撃
	Skill,			// スキル
	Ultimate,		// 必殺技

	//--------------------------
	// 移動関連
	//--------------------------
	Dash,			// ダッシュ
	Dodge,			// 回避

	//--------------------------
	// その他
	//--------------------------
	Death,			// 死亡
	Explosion,		// 爆発
	LockOn,			// ロックオン
};