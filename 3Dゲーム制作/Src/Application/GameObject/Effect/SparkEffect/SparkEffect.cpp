#include "SparkEffect.h"

#include <Application/main.h>
#include <Application/GameObject/Camera/CameraBase.h>

//==============================================================
// 初期化
//==============================================================
void SparkEffect::Init(
	const Math::Vector3& pos,
	const Math::Vector3& direction)
{
	EffectBase::Init(
		EffectType::Spark,
		pos
	);

	//==========================================================
	// 攻撃方向
	//==========================================================
	m_direction = direction;

	m_direction.y = 0.0f;

	if (m_direction.LengthSquared() > 0.0001f)
	{
		m_direction.Normalize();
	}
	else
	{
		m_direction = Math::Vector3::Forward;
	}

	//==========================================================
	// 再生時間
	//==========================================================
	m_lifeTime = 0.25f;

	//==========================================================
	// ポリゴン生成
	//==========================================================
	m_polygon =
		std::make_shared<SparkEffectPolygon>();

	m_polygon->SetVertices(
		1.0f,
		0.08f
	);

	//==========================================================
	// 粒子生成
	//==========================================================
	CreateParticles();
}


//==============================================================
// 粒子生成
//==============================================================
void SparkEffect::CreateParticles()
{
	m_particles.clear();

	const int particleCount = 12;

	//==========================================================
	// 攻撃方向に対して左右方向を作る
	//==========================================================
	Math::Vector3 side =
		Math::Vector3::Up.Cross(m_direction);

	if (side.LengthSquared() > 0.0001f)
	{
		side.Normalize();
	}
	else
	{
		side = Math::Vector3::Right;
	}

	//==========================================================
	// 粒子生成
	//==========================================================
	for (int i = 0; i < particleCount; ++i)
	{
		SparkParticle particle;

		//======================================================
		// 発生位置
		//======================================================
		particle.pos = GetPos();

		//======================================================
		// 前方向への飛び散り
		//======================================================
		float forwardPower =
			0.3f +
			static_cast<float>(rand() % 100) / 100.0f;

		//======================================================
		// 左右への飛び散り
		//======================================================
		float sidePower =
			(static_cast<float>(rand() % 200) / 100.0f) - 1.0f;

		//======================================================
		// 上方向への飛び散り
		//======================================================
		float upPower =
			0.2f +
			static_cast<float>(rand() % 100) / 100.0f;

		//======================================================
		// 飛び散る方向
		//======================================================
		Math::Vector3 dir =
			m_direction * forwardPower;

		dir +=
			side * sidePower * 0.8f;

		dir.y +=
			upPower;

		if (dir.LengthSquared() > 0.0001f)
		{
			dir.Normalize();
		}

		//======================================================
		// 初速
		//======================================================
		particle.velocity =
			dir *
			(
				3.0f +
				static_cast<float>(rand() % 300) / 100.0f
				);

		//======================================================
		// 火花の長さ
		//======================================================
		particle.length =
			0.25f +
			static_cast<float>(rand() % 30) / 100.0f;

		//======================================================
		// 火花の太さ
		//======================================================
		particle.width =
			0.02f +
			static_cast<float>(rand() % 3) / 100.0f;

		m_particles.push_back(particle);
	}
}


//==============================================================
// 更新
//==============================================================
void SparkEffect::Update()
{
	EffectBase::Update();

	const float dt =
		Application::Instance().GetDeltaTime();

	for (auto& particle : m_particles)
	{
		//======================================================
		// 移動
		//======================================================
		particle.pos +=
			particle.velocity * dt;

		//======================================================
		// 重力
		//======================================================
		particle.velocity.y -=
			10.0f * dt;
	}
}


//==============================================================
// 描画
//==============================================================
void SparkEffect::DrawEffect()
{
	if (!m_polygon)
	{
		return;
	}

	auto camera =
		m_wpCamera.lock();

	if (!camera)
	{
		return;
	}

	//==========================================================
	// 火花描画
	//==========================================================
	for (const auto& particle : m_particles)
	{
		Math::Vector3 dir =
			particle.velocity;

		if (dir.LengthSquared() < 0.0001f)
		{
			continue;
		}

		dir.Normalize();

		//======================================================
		// 火花の向き
		//======================================================
		Math::Vector3 up =
			Math::Vector3::Up;

		if (std::abs(dir.Dot(up)) > 0.95f)
		{
			up = Math::Vector3::Right;
		}

		Math::Vector3 right =
			up.Cross(dir);

		right.Normalize();

		up =
			dir.Cross(right);

		up.Normalize();

		//======================================================
		// ワールド行列
		//======================================================
		Math::Matrix mat;

		mat.Right(right);
		mat.Up(up);
		mat.Forward(dir);

		//======================================================
		// 火花の長さ・太さ
		//======================================================
		mat *=
			Math::Matrix::CreateScale(
				particle.length,
				particle.width,
				1.0f
			);

		//======================================================
		// 位置
		//======================================================
		mat.Translation(
			particle.pos
		);

		//======================================================
		// 描画
		//======================================================
		KdShaderManager::Instance()
			.m_StandardShader
			.DrawPolygon(
				*m_polygon,
				mat,
				Math::Color(
					1.0f,
					0.65f,
					0.1f,
					1.0f
				)
			);
	}
}


//==============================================================
// 頂点設定
//==============================================================
void SparkEffectPolygon::SetVertices(
	float length,
	float width)
{
	m_vertices.clear();

	float half =
		length * 0.5f;

	float halfWidth =
		width * 0.5f;

	//==========================================================
	// 左上
	//==========================================================
	Vertex v0;

	v0.pos = {
		-half,
		 halfWidth,
		0.0f
	};

	v0.UV = {
		0.0f,
		0.0f
	};

	//==========================================================
	// 右上
	//==========================================================
	Vertex v1;

	v1.pos = {
		 half,
		 halfWidth,
		0.0f
	};

	v1.UV = {
		1.0f,
		0.0f
	};

	//==========================================================
	// 左下
	//==========================================================
	Vertex v2;

	v2.pos = {
		-half,
		-halfWidth,
		0.0f
	};

	v2.UV = {
		0.0f,
		1.0f
	};

	//==========================================================
	// 右下
	//==========================================================
	Vertex v3;

	v3.pos = {
		 half,
		-halfWidth,
		0.0f
	};

	v3.UV = {
		1.0f,
		1.0f
	};

	//==========================================================
	// 三角形1
	//==========================================================
	m_vertices.push_back(v0);
	m_vertices.push_back(v1);
	m_vertices.push_back(v2);

	//==========================================================
	// 三角形2
	//==========================================================
	m_vertices.push_back(v2);
	m_vertices.push_back(v1);
	m_vertices.push_back(v3);
}